<?php

namespace Database\Seeders;

use App\Http\Controllers\CommentController;
use App\Models\Comment;
use App\Models\Post;
use App\Models\Tag;
use App\Models\User;
use App\Models\Vote;
use Carbon\Carbon;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use RuntimeException;

/** Opt-in, additive fixtures for local portfolio screenshots; never production data. */
class PortfolioDemoSeeder extends Seeder
{
    public function run(): void
    {
        if (! app()->environment(['local', 'testing'])) {
            throw new RuntimeException('Portfolio fixtures are restricted to local and testing environments.');
        }

        if (User::withTrashed()->where('username', 'demo_sara')->exists()) {
            $this->command?->info('Portfolio fixtures already exist; nothing was changed.');

            return;
        }

        $originalClock = Carbon::getTestNow();
        $originalUser = Auth::user();
        $originalBroadcast = config('broadcasting.default');
        $base = Carbon::now()->startOfMinute();
        // Persist normal notifications, but do not contact a socket server during fixture creation.
        config(['broadcasting.default' => 'null']);

        try {
            DB::transaction(function () use ($base) {
                if (! DB::table('roles')->exists()) {
                    $this->call(RoleSeeder::class);
                }
                $this->call(TagSeeder::class);
                $names = [
                    ['sara', 'Sara Haddad', 'Databases, distributed systems, and reproducible software experiments.'],
                    ['omar', 'Omar Nasser', 'Backend engineering and the design of reliable APIs.'],
                    ['leila', 'Leila Mansour', 'Statistics, scientific reasoning, and careful data interpretation.'],
                    ['adam', 'Adam Khalil', 'Machine learning evaluation and responsible research practice.'],
                    ['maya', 'Maya Saleh', 'Accessible interfaces and human-centered software design.'],
                    ['yusuf', 'Yusuf Karim', 'Application security and practical threat modeling.'],
                ];
                $users = [];
                Carbon::setTestNow($base->copy()->subDays(14));
                foreach ($names as [$handle, $name, $bio]) {
                    $users[] = User::factory()->create([
                        'username' => 'demo_'.$handle,
                        'email' => 'demo_'.$handle.'@knowverse.test',
                        'full_name' => $name,
                        'academic_title' => null,
                        'bio' => $bio.' Fictional portfolio demonstration account.',
                        'password' => Str::random(48),
                        'last_login_at' => null,
                        'reputation_points' => 0,
                    ]);
                }

                $fixtures = require __DIR__.'/data/portfolio-discussions.php';
                $posts = [];
                $comments = [];
                foreach ($fixtures as $index => $fixture) {
                    // Newest discussions lead the existing feed without pinning or replacing data.
                    Carbon::setTestNow($base->copy()->subHours(24 - $index * 2));
                    $post = Post::create([
                        'user_id' => $users[$fixture['author']]->id,
                        'title' => $fixture['title'],
                        'body' => $fixture['body'],
                        'status' => Post::STATUS_PUBLISHED,
                        'is_hidden' => false,
                    ]);
                    $post->tags()->sync(Tag::whereIn('name', $fixture['tags'])->pluck('id'));
                    $posts[] = $post;
                    foreach ($fixture['comments'] as $offset => [$author, $body]) {
                        Carbon::setTestNow($base->copy()->subHours(24 - $index * 2)->addMinutes(15 + $offset * 10));
                        $comments[$index][] = Comment::create([
                            'post_id' => $post->id,
                            'user_id' => $users[$author]->id,
                            'body' => $body,
                        ]);
                    }
                    foreach ($users as $voter) {
                        if ($voter->id !== $post->user_id) {
                            Vote::castVote($voter, $post, 1);
                        }
                    }
                }

                // Recent, varied ledger events generated by the same domain operations as the UI.
                Carbon::setTestNow($base->copy()->subMinutes(95));
                $answer = $comments[8][0]; // Sara's answer to Omar's transaction question.
                Auth::setUser($users[1]);
                app(CommentController::class)->markAsBest($answer);
                foreach ([2, 3, 4] as $offset => $voter) {
                    Carbon::setTestNow($base->copy()->subMinutes(80 - $offset * 10));
                    Vote::castVote($users[$voter], $answer, 1);
                }
                Carbon::setTestNow($base->copy()->subMinutes(45));
                Comment::create([
                    'post_id' => $posts[9]->id,
                    'parent_id' => $comments[9][0]->id,
                    'user_id' => $users[0]->id,
                    'body' => 'Agreed. I would keep the unique constraint as the final guard, then test both duplicate delivery and a rollback after the ledger insert. The balance should match the sum after every committed operation.',
                ]);
                Carbon::setTestNow($base->copy()->subMinutes(30));
                Vote::retract($users[5], $posts[9]);
                Carbon::setTestNow($base->copy()->subMinutes(20));
                Auth::setUser($users[0]);
                app(CommentController::class)->markAsBest($comments[9][0]);

                foreach ($users as $user) {
                    if ((int) $user->fresh()->reputation_points !== (int) $user->reputations()->sum('delta')) {
                        throw new RuntimeException('Portfolio ledger balance verification failed.');
                    }
                }
                $this->command?->info('Created 6 fictional scholars and 10 discussions. Ledger sums verified for all six accounts.');
                $this->command?->info('Featured discussion: /posts/'.$posts[9]->id.'; ledger scholar: '.$users[0]->username.' (ID '.$users[0]->id.').');
            });
        } finally {
            Carbon::setTestNow($originalClock);
            config(['broadcasting.default' => $originalBroadcast]);
            if ($originalUser) {
                Auth::setUser($originalUser);
            } else {
                Auth::forgetUser();
            }
        }
    }
}
